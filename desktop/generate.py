#!/usr/bin/env python3
"""Generates the two files in shared/ that are not committed: Migrations.js (the SQL migrations of
../core/storage/migrations/) and FirebaseConfig.js (project id and API key from firebase.local.json).
Used by install.sh (Plasma widget) and by CMake (tray app), so both builds get the same files.
Plain Python, runs the same on Linux and Windows."""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read(path):
    return path.read_text(encoding="utf-8")


def write(path, text):
    # always LF and UTF-8, so the output is identical on every OS
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def statements(sql):
    sql = re.sub(r"--[^\n]*", "", sql)
    sql = re.sub(r"\n[ \t]*(?=\n)", "", sql)
    return [s.strip() for s in sql.split(";") if s.strip()]


def generate_migrations(src, out):
    migrations, legacy = [], None
    for f in sorted(src.glob("*.sql")):
        if f.name.startswith("legacy_plasmoid_to_001"):
            legacy = statements(read(f))
            continue
        m = re.match(r"(\d+)_", f.name)
        if m:
            migrations.append({"version": int(m.group(1)), "statements": statements(read(f))})
    if legacy is None or not migrations:
        sys.exit("generate.py: no migrations found in " + str(src))
    migrations.sort(key=lambda m: m["version"])

    write(out,
          ".pragma library\n"
          "// GENERATED by desktop/generate.py from core/storage/migrations/*.sql, do not edit or commit.\n\n"
          "var migrations = " + json.dumps(migrations, indent=4) + "\n\n"
          "// upgrade for the first plasmoid builds (integer ids), ends at version 1\n"
          "var legacyToV1 = " + json.dumps(legacy, indent=4) + "\n")
    print("generated", out, "with versions", [m["version"] for m in migrations])


def generate_firebase_config(local, rc, fb, out):
    # Firebase settings for sign-in: project id from core/firebase/.firebaserc, API key from the local,
    # uncommitted firebase.local.json (copy firebase.local.example.json). Without it sign-in is disabled.
    cfg = json.loads(read(local)) if local.exists() else {}
    project = cfg.get("projectId") or json.loads(read(rc))["projects"]["default"]
    api_key = cfg.get("apiKey", "")
    emulator = bool(cfg.get("emulator", False))

    if emulator:
        emulators = json.loads(read(fb))["emulators"]
        auth = "http://localhost:%d/identitytoolkit.googleapis.com/v1" % emulators["auth"]["port"]
        token = "http://localhost:%d/securetoken.googleapis.com/v1" % emulators["auth"]["port"]
        firestore = "http://localhost:%d/v1" % emulators["firestore"]["port"]
        api_key = api_key or "demo-key"
    else:
        auth = "https://identitytoolkit.googleapis.com/v1"
        token = "https://securetoken.googleapis.com/v1"
        firestore = "https://firestore.googleapis.com/v1"

    write(out,
          ".pragma library\n"
          "// GENERATED by desktop/generate.py from firebase.local.json, do not edit or commit.\n\n"
          "var configured = " + json.dumps(bool(api_key)) + "\n"
          "var apiKey = " + json.dumps(api_key) + "\n"
          "var projectId = " + json.dumps(project) + "\n"
          "var emulator = " + json.dumps(emulator) + "\n"
          "var authUrl = " + json.dumps(auth) + "\n"
          "var tokenUrl = " + json.dumps(token) + "\n"
          "var firestoreUrl = " + json.dumps(firestore) + "\n")
    print("generated", out, "(emulator)" if emulator else "(real project)" if api_key else "(no API key: sign-in disabled)")


if __name__ == "__main__":
    generate_migrations(HERE / "../core/storage/migrations", HERE / "shared/Migrations.js")
    generate_firebase_config(HERE / "firebase.local.json",
                             HERE / "../core/firebase/.firebaserc",
                             HERE / "../core/firebase/firebase.json",
                             HERE / "shared/FirebaseConfig.js")
