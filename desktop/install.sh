#!/usr/bin/env bash
# Installs (or upgrades) the plasmoid.
#
# The plasmoid package cannot read ../core at runtime (QML may not read local files, and only
# plasmoid/ is installed), so the shared SQL migrations from core/storage/migrations/ are copied
# in here as a generated JS module, plasmoid/contents/ui/Migrations.js (not committed).
# Run this after every change in core/storage/migrations/ and instead of calling kpackagetool6 by hand.
set -euo pipefail
cd "$(dirname "$0")"

python3 -I - ../core/storage/migrations plasmoid/contents/ui/Migrations.js <<'PY'
import json, re, sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])

def statements(sql):
    sql = re.sub(r"--[^\n]*", "", sql)
    sql = re.sub(r"\n[ \t]*(?=\n)", "", sql)
    return [s.strip() for s in sql.split(";") if s.strip()]

migrations, legacy = [], None
for f in sorted(src.glob("*.sql")):
    if f.name.startswith("legacy_plasmoid_to_001"):
        legacy = statements(f.read_text())
        continue
    m = re.match(r"(\d+)_", f.name)
    if m:
        migrations.append({"version": int(m.group(1)), "statements": statements(f.read_text())})
if legacy is None or not migrations:
    sys.exit("install.sh: no migrations found in " + str(src))
migrations.sort(key=lambda m: m["version"])

out.write_text(
    ".pragma library\n"
    "// GENERATED by desktop/install.sh from core/storage/migrations/*.sql, do not edit or commit.\n\n"
    "var migrations = " + json.dumps(migrations, indent=4) + "\n\n"
    "// upgrade for the first plasmoid builds (integer ids), ends at version 1\n"
    "var legacyToV1 = " + json.dumps(legacy, indent=4) + "\n")
print("generated", out, "with versions", [m["version"] for m in migrations])
PY

if kpackagetool6 -t Plasma/Applet -l 2>/dev/null | grep -q "org.kde.plasma.chaosnoteviewer"; then
    kpackagetool6 -t Plasma/Applet -u plasmoid
else
    kpackagetool6 -t Plasma/Applet -i plasmoid
fi
echo "Done. If the widget did not refresh: plasmashell --replace &"
